export function buildSystemPrompt(params: {
  subjectId: string;
  contextBlock: string; // формируется из buildStudentContext
}): string {
  const { BASE_TEACHER_PROMPT } = require("./basePrompt");
  const subjectBlock = SUBJECT_PROMPTS[params.subjectId] ?? "";

  return `${BASE_TEACHER_PROMPT}

---
${subjectBlock}

---
КОНТЕКСТ УЧЕНИКА (используй для адаптации, не проговаривай вслух дословно)

${params.contextBlock}`;
}
